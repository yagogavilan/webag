import { launch, appSession, appLogin, appGo, call, sql, vis, adminToken } from './lib.mjs';
import { Recorder, imagesReady } from './clip-lib.mjs';
import * as P from './pedido.mjs';
const OUT = process.env.OUT ?? '/tmp/webag-mkt/work/out';
const EMAIL = process.env.EMAIL ?? 'marina.mkt@seed.webag.local';
const ct = await P.login(EMAIL);
const mt = await P.login(P.MERCHANT);
const at = await adminToken();
const cid = await P.ensureCourier(at);
const order = await P.placeOrder(ct, [['Camiseta básica algodão', 1], ['Bermuda de sarja', 1]]);
await P.payOrder(order, ct);
await P.merchantApi(mt, order.id, 'accept');
await P.merchantApi(mt, order.id, 'status', { status: 'in_preparation' });
sql(`update orders set eta_from_at = now() + interval '14 minutes', eta_to_at = now() + interval '39 minutes' where id='${order.id}'`);
console.log('pedido', order.number);
const b = await launch();
const { context, page } = await appSession(b, { dsf: 3 });
const cdp = await context.newCDPSession(page);
await appLogin(page, EMAIL);
await page.addStyleTag({ content: '[data-testid="order.delivery-code"]{display:none !important}' });
await appGo(page, `/order/${order.id}`);
await vis(page, 'order.timeline');
await page.waitForTimeout(6500);
const status = () => page.evaluate(() => document.querySelector('[data-testid="order.status"]')?.innerText ?? '');
console.log('A:', await status());
const waitChange = async (from) => { for (let i = 0; i < 120; i++) { const s = await status(); if (s && s !== from) return s; await page.waitForTimeout(250); } throw new Error('status nao mudou de ' + from); };
const rec = new Recorder(page, cdp, { out: `${OUT}/app-acompanhar.mp4`, crf: 20, clip: { x: 0, y: 0, width: 390, height: 844, scale: 3 } });
await rec.begin();
await rec.run(1.1);
const A = await status();
await P.merchantApi(mt, order.id, 'status', { status: 'ready_for_collection', volumes: 1 });
console.log('B:', await waitChange(A));
await page.waitForTimeout(300);
await rec.run(1.2);
const Bs = await status();
const did = P.deliveryOf(order.id);
await P.assign(at, did, cid);
await P.courierStep(at, did, 'confirm');
await P.courierStep(at, did, 'picked_up');
console.log('C:', await waitChange(Bs));
await page.waitForTimeout(300);
const left = 4.0 - rec.frames / 30;
await rec.run(Math.max(left, 0.5));
console.log(await rec.end());
await b.close();
