import { launch, appSession, appLogin, appGo, call, vis, tap } from './lib.mjs';
import { Recorder, markScroller, setScroll, imagesReady, tapAt, scrollBy, rectOf, ease } from './clip-lib.mjs';
import * as P from './pedido.mjs';
const OUT = process.env.OUT ?? '/tmp/webag-mkt/work/out';
const EMAIL = process.env.EMAIL ?? 'marina.mkt@seed.webag.local';
const ct = await P.login(EMAIL);
await call('DELETE', '/v1/cart', null, ct);
const TENIS = 'd39d918e-26a6-4420-9d59-c6f112017e29';
const b = await launch();
const { context, page } = await appSession(b, { dsf: 3 });
const cdp = await context.newCDPSession(page);
await appLogin(page, EMAIL);
await appGo(page, `/product/${TENIS}`);
await vis(page, 'product.add');
await page.waitForTimeout(6500); // toasts somem
const rec = new Recorder(page, cdp, { out: `${OUT}/app-sacola.mp4`, crf: 20, clip: { x: 0, y: 0, width: 390, height: 844, scale: 3 } });
await rec.begin();
await imagesReady(page, rec);
const chip = await page.evaluate(() => { const els = [...document.querySelectorAll('[data-testid^="product.variant-"]')].filter((e) => e.getAttribute('data-testid') !== 'product.variant-error' && e.getAttribute('aria-disabled') !== 'true' && e.getClientRects().length); const r = els[0].getBoundingClientRect(); return { id: els[0].getAttribute('data-testid'), cx: r.x + r.width / 2, cy: r.y + r.height / 2 }; });
console.log(chip);
await rec.run(0.35);
await tapAt(rec, page, chip.cx, chip.cy, async () => { await page.waitForTimeout(500); });
await rec.run(0.2);
const add = await rectOf(page, '[data-testid="product.add"]');
await tapAt(rec, page, add.cx, add.cy, async () => {
  await page.getByText('Ver sacola', { exact: true }).first().waitFor({ timeout: 20000 });
  await page.waitForTimeout(400);
});
await rec.run(0.35);
const ver = await page.evaluate(() => { const els = [...document.querySelectorAll('*')].filter((e) => e.children.length === 0 && e.textContent.trim() === 'Ver sacola' && e.getClientRects().length); const r = els[0].getBoundingClientRect(); return { cx: r.x + r.width / 2, cy: r.y + r.height / 2 }; });
await tapAt(rec, page, ver.cx, ver.cy, async () => {
  await vis(page, 'cart.total');
  await page.waitForTimeout(900);
  await imagesReady(page, rec);
});
const left = 3.0 - rec.frames / 30;
console.log('frames', rec.frames, 'resta', left);
if (left > 0) await rec.run(left);
console.log(await rec.end());
await b.close();
