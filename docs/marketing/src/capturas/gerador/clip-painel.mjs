import { launch, painelLogin, painelGo, refreshDemoTimes, WEB, call, sql, MODA } from './lib.mjs';
import { Recorder, ease, clamp01 } from './clip-lib.mjs';
import { installCursor, cursorAt, rectOf } from './rec.mjs';
import * as P from './pedido.mjs';
const OUT = process.env.OUT ?? '/tmp/webag-mkt/work/out';
const ct = await P.login(process.env.CUST ?? 'joana.mkt@seed.webag.local');
const mt = await P.login(P.MERCHANT);
for (const o of (await call('GET', `/v1/stores/${MODA}/orders?scope=new&limit=50`, null, mt)).data.data) if (o.status === 'received') await P.merchantApi(mt, o.id, 'accept');
refreshDemoTimes();
const novo = await P.placeOrder(ct, [['Camiseta básica algodão', 1], ['Bermuda de sarja', 1]]);
console.log('novo', novo.number);
const b = await launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 810 }, deviceScaleFactor: 4 / 3, locale: 'pt-BR', timezoneId: 'America/Sao_Paulo' });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await painelLogin(page, P.MERCHANT);
await painelGo(page, '/lojista/pedidos', false);
// liga o som (banner "Ligar som"), se existir
await page.getByText('Ligar som', { exact: true }).first().click({ timeout: 3000 }).catch(() => console.log('sem botao ligar som'));
await page.waitForTimeout(1500);
console.log('som:', await page.evaluate(() => document.body.innerText.match(/Som (ligado|desligado)/)?.[0]));
await installCursor(page);
const rec = new Recorder(page, cdp, { out: `${OUT}/painel-pedido-novo.mp4`, crf: 19, clip: { x: 0, y: 0, width: 1440, height: 810, scale: 4 / 3 } });
await rec.begin();
const start = { x: 1060, y: 560 };
await cursorAt(page, start.x, start.y, 1, 0);
await rec.run(1.0, async () => cursorAt(page, start.x, start.y, 1, 0));
await P.payOrder(novo, ct);
// espera o alerta (tempo real); o video corta direto para ele
await page.waitForSelector('[data-testid="lojista.alert.modal"]', { timeout: 40000 });
await page.waitForTimeout(700);
await rec.run(1.2, async () => cursorAt(page, start.x, start.y, 1, 0));
const btn = await rectOf(page, '[data-testid="lojista.alert.accept"]');
console.log('aceitar', btn);
const to = { x: btn.cx + 6, y: btn.cy + 4 };
await rec.run(0.9, async (t) => { const k = ease.inOutSine(t); await cursorAt(page, start.x + (to.x - start.x) * k, start.y + (to.y - start.y) * k, 1, 0); });
await rec.run(0.2, async () => cursorAt(page, to.x, to.y, 1, 0));
await rec.run(0.25, async (t) => cursorAt(page, to.x, to.y, 1, ease.out(t) * 0.9));
await page.mouse.move(to.x, to.y);
await page.mouse.click(to.x, to.y);
await page.waitForSelector('[data-testid="lojista.alert.modal"]', { state: 'detached', timeout: 20000 });
await page.waitForTimeout(900);
const left = 4.0 - rec.frames / 30;
console.log('frames', rec.frames, 'resta', left);
await rec.run(Math.max(left, 0.3), async () => cursorAt(page, to.x, to.y, 1, 0));
console.log(await rec.end());
await b.close();
